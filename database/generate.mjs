import { writeFile,readFile } from 'node:fs/promises';
import { tables } from './schema.mjs';
for(const migration of [2,3]){
const selected=tables.filter(t=>(t.migration??2)===migration);
const sql=[`-- Generated by node database/generate.mjs from database/schema.mjs and guards.sql.
-- SRS-FIN-001 v1.0: structural coverage includes M and S; services remain disabled.
${migration===2?`CREATE DOMAIN mizan.exact_amount AS numeric
  CHECK (VALUE::text NOT IN ('NaN','Infinity','-Infinity') AND abs(VALUE)<1e22 AND scale(VALUE)<=8);`:''}
`];
const relations=[];
for(const t of selected){
 const scoped=['tenant','entity'].includes(t.scope), base=t.scope==='catalog'?[]:['id uuid PRIMARY KEY DEFAULT gen_random_uuid()'];
 if(scoped)base.push('tenant_id uuid NOT NULL');
 if(t.scope==='entity')base.push('entity_id uuid NOT NULL');
 if(t.scope!=='catalog')base.push('created_at timestamptz NOT NULL DEFAULT now()');
 const constraints=[...t.constraints];
 if(scoped){constraints.push('UNIQUE(tenant_id,id)','FOREIGN KEY(tenant_id) REFERENCES mizan.tenants(id)');}
 if(t.scope==='entity')constraints.push('UNIQUE(tenant_id,entity_id,id)','FOREIGN KEY(tenant_id,entity_id) REFERENCES mizan.legal_entities(tenant_id,id)');
 const local=constraints.filter(c=>!c.startsWith('FOREIGN KEY'));
 relations.push(...constraints.filter(c=>c.startsWith('FOREIGN KEY')).map(c=>`ALTER TABLE mizan.${t.name} ADD ${c};`));
 sql.push(`-- ${t.requirements}\nCREATE TABLE mizan.${t.name} (\n  ${[...base,...t.columns,...local].join(',\n  ')}\n);`);
 sql.push(`COMMENT ON TABLE mizan.${t.name} IS '${t.requirements.replaceAll("'","''")} — see docs/DATABASE-SRS.md';`);
}
sql.push(...relations);
if(migration===2)sql.push('ALTER TABLE mizan.analysis_narratives ADD FOREIGN KEY(tenant_id,entity_id,model_run_id) REFERENCES mizan.ai_narrative_runs(tenant_id,entity_id,id);');
sql.push(await readFile(new URL(migration===2?'./guards.sql':'./hardening.sql',import.meta.url),'utf8'));
for(const t of selected){
 const hasEntity=t.scope==='entity'||t.columns.some(c=>c.startsWith('entity_id '));
 if(t.scope!=='catalog'){
  sql.push(`ALTER TABLE mizan.${t.name} ENABLE ROW LEVEL SECURITY;\nALTER TABLE mizan.${t.name} FORCE ROW LEVEL SECURITY;`);
  const clause=t.scope==='identity'?`${t.userColumn??'id'}::text=current_setting('mizan.user_id',true)`:
   `${t.scope==='tenantRoot'?'id':'tenant_id'}::text=current_setting('mizan.tenant_id',true)${hasEntity?" AND (entity_id IS NULL OR entity_id::text=ANY(string_to_array(current_setting('mizan.entity_ids',true),',')))":''}`;
  sql.push(`CREATE POLICY scoped_access ON mizan.${t.name} USING (${clause}) WITH CHECK (${clause});`);
  sql.push(`CREATE TRIGGER identity_immutable BEFORE UPDATE ON mizan.${t.name} FOR EACH ROW EXECUTE FUNCTION mizan.guard_identity();`);
 }
 if(t.appendOnly)sql.push(`CREATE TRIGGER append_only BEFORE UPDATE OR DELETE ON mizan.${t.name} FOR EACH ROW EXECUTE FUNCTION mizan.reject_mutation();`);
 if(t.immutableColumns)sql.push(`CREATE TRIGGER source_identity_immutable BEFORE UPDATE ON mizan.${t.name} FOR EACH ROW EXECUTE FUNCTION mizan.guard_columns(${t.immutableColumns.map(c=>`'${c}'`).join(',')});`);
 if(t.amountColumns)sql.push(`CREATE TRIGGER currency_precision BEFORE INSERT OR UPDATE ON mizan.${t.name} FOR EACH ROW EXECUTE FUNCTION mizan.guard_currency_precision(${t.amountColumns.map(c=>`'${c}'`).join(',')});`);
 if(t.datasetColumn)sql.push(`CREATE TRIGGER dataset_editable BEFORE INSERT OR UPDATE OR DELETE ON mizan.${t.name} FOR EACH ROW EXECUTE FUNCTION mizan.guard_dataset_child('${t.datasetColumn}');`);
 if(t.outputColumn)sql.push(`CREATE TRIGGER output_editable BEFORE INSERT OR UPDATE OR DELETE ON mizan.${t.name} FOR EACH ROW EXECUTE FUNCTION mizan.guard_output_child('${t.outputColumn}');`);
 // Every referencing FK gets a leading-column index unless a PK/UNIQUE already supplies it.
 const all=[...t.constraints];
 if(t.scope==='entity')all.push('FOREIGN KEY(tenant_id,entity_id) REFERENCES mizan.legal_entities(tenant_id,id)');
 let index=0;
 for(const c of all.filter(c=>c.startsWith('FOREIGN KEY'))){
  const columns=c.match(/FOREIGN KEY\s*\(([^)]+)\)/)[1];
  sql.push(`CREATE INDEX ${t.name.slice(0,40)}_fk_${++index} ON mizan.${t.name} (${columns});`);
 }
}
sql.push(`REVOKE ALL ON ALL TABLES IN SCHEMA mizan FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA mizan FROM PUBLIC;
REVOKE ALL ON SCHEMA mizan FROM PUBLIC;`);
await writeFile(new URL(migration===2?'../migrations/002_srs_relational_model.sql':'../migrations/003_srs_integrity_guards.sql',import.meta.url),sql.join('\n\n')+'\n');
}
const sections=tables.map(t=>`### ${t.name}\n\nScope: **${t.scope}**. Requirements: ${t.requirements}.\n\n${t.scope==='catalog'?'':'Standard fields: `id uuid`, `created_at timestamptz`'+(['tenant','entity'].includes(t.scope)?', `tenant_id uuid`':'')+(t.scope==='entity'?', `entity_id uuid`':'')+'.\n\n'}| Field | SQL definition |\n|---|---|\n${t.columns.map(c=>{const [field,...rest]=c.split(' ');return `| \`${field}\` | \`${rest.join(' ').replaceAll('|','\\|')}\` |`;}).join('\n')}\n\nConstraints:\n\n${t.constraints.map(c=>`- \`${c}\``).join('\n')||'- Primary key.'}\n`);
await writeFile(new URL('../docs/DATABASE-FIELDS.md',import.meta.url),'# SRS database field dictionary\n\nGenerated from `database/schema.mjs`. '+tables.length+' new business tables. Composite scope keys and foreign-key indexes are added by the generator. Runtime guards are described in DATABASE-SRS.md. Legacy `financial_snapshots` and migration metadata are separate.\n\n'+sections.join('\n'));
await writeFile(new URL('../docs/database-tables.json',import.meta.url),JSON.stringify(tables.map(({name,scope,requirements})=>({name,scope,requirements})),null,2)+'\n');
console.log(`Generated migrations 002/003 and field dictionary for ${tables.length} business tables`);
